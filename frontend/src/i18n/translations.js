// Fallback helper function to get translated text with default fallback
export function getTranslation(lang, key) {
  const targetDict = translations[lang] || translations.hi || translations.en
  if (targetDict && targetDict[key]) {
    return targetDict[key]
  }
  // Try Hindi if regional Indian language is missing specific key
  if (translations.hi && translations.hi[key]) {
    return translations.hi[key]
  }
  // Ultimate fallback to English
  return translations.en[key] || key
}
